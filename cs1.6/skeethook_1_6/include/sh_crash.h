#ifndef SH_CRASH_H
#define SH_CRASH_H

#include "sh_types.h"

/* Ставит обработчик необработанных исключений.
   При падении пишет рядом с hl.exe файл skeethook_crash.log
   и кладёт тот же текст в буфер обмена - чтобы можно было
   просто вставить (Ctrl+V) в чат и не искать файл руками. */
void sh_crash_init(void);

/* Последний отчёт, лежит в статическом буфере. Нужен, чтобы
   обработчик не аллоцировал память в момент падения. */
const char *sh_crash_last_report(void);

/* Записывает в отчёт этап инициализации. Мы помечаем, до какого
   места дошли, - при падении видно, что успело выполниться. */
void sh_crash_stage(const char *stage);

/* Проверка без падения: тот же формат отчёта, тот же файл и буфер.
   Нужна, чтобы убедиться, что механизм работает, до реального краша. */
void sh_c_crash_test(void);

#endif
